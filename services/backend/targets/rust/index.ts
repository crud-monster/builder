import * as fs from 'fs'
import * as path from 'path'
import type { BackendTarget, BackendTargetContext } from '../types'
import { databaseProvider } from '../../database/schema'
import { generateRustModels } from './generators/models'

function template(name: string): string {
    return fs.readFileSync(path.join(__dirname, 'templates', name), 'utf8')
}

function crateName(name: string): string {
    const basename = path.posix.basename(name.replace(/\\/g, '/'))
    const slug = basename.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
    return `crud-${slug || 'rust-project'}`
}

async function generate({ name, source, outDir, models, config }: BackendTargetContext): Promise<void> {
    const provider = databaseProvider(config.database ?? 'postgresql')
    if (provider !== 'postgresql') throw new Error(`Rust target currently supports only postgresql, received ${provider}`)
    const overrides = Object.keys(config).filter(key => !['target', 'database', 'integrationTestsEnable'].includes(key) && config[key] !== undefined)
    if (overrides.length || config.integrationTestsEnable) throw new Error('Rust model scaffold does not support integration test generation or TypeScript template overrides')
    // Validate and render before modifying the output project.
    const rendered = generateRustModels(models)
    const initial = { '.gitignore': template('gitignore'), 'Cargo.toml': template('Cargo.toml').replace('__CRATE_NAME__', crateName(name)), 'README.md': template('README.md'), 'src/lib.rs': template('src/lib.rs'), 'src/main.rs': template('src/main.rs') }
    const marker = path.join(outDir, '.gmb-project.json')
    const directories = [outDir, path.join(outDir, 'src'), path.join(outDir, 'src/generated')]
    const files = ['.gitignore', 'Cargo.toml', 'README.md', 'src/lib.rs', 'src/main.rs', 'src/generated/mod.rs', 'src/generated/models.rs', 'src/generated/source.schema', '.gmb-project.json']
    for (const candidate of [...directories, ...files.map(file => path.join(outDir, file))]) {
        try {
            const status = fs.lstatSync(candidate)
            if (status.isSymbolicLink()) throw new Error(`Rust output cannot overwrite a symbolic link: ${candidate}`)
            if (directories.includes(candidate) ? !status.isDirectory() : !status.isFile()) throw new Error(`Unexpected file type in Rust output: ${candidate}`)
        } catch (error) {
            if (error.code !== 'ENOENT') throw error
        }
    }
    if (fs.existsSync(outDir)) {
        if (!fs.lstatSync(outDir).isDirectory()) throw new Error('Rust output must be a directory')
        if (fs.readdirSync(outDir).length && !fs.existsSync(marker)) throw new Error('Choose a new output directory or an existing builder-generated Rust project')
        if (fs.existsSync(marker)) {
            const previous = JSON.parse(fs.readFileSync(marker, 'utf8'))
            if (previous.format !== 1 || previous.target !== 'rust' || previous.database !== provider) throw new Error('Incompatible Rust project metadata')
        }
    }
    for (const directory of directories) fs.mkdirSync(directory, { recursive: true })
    fs.writeFileSync(marker, JSON.stringify({ format: 1, target: 'rust', database: provider }, null, 2) + '\n')

    for (const [file, content] of Object.entries(initial)) {
        const filename = path.join(outDir, file)
        if (!fs.existsSync(filename)) fs.writeFileSync(filename, content, { flag: 'wx' })
    }
    fs.writeFileSync(path.join(outDir, 'src/generated/mod.rs'), '// Generated by CRUD Monster Builder.\npub mod models;\n')
    fs.writeFileSync(path.join(outDir, 'src/generated/models.rs'), rendered)
    fs.writeFileSync(path.join(outDir, 'src/generated/source.schema'), source)
}

export const rustTarget: BackendTarget = { name: 'rust', generate }
